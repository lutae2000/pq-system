CREATE TABLE IF NOT EXISTS bid_notices (
    bid_seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    g2b_bid_ntce_no VARCHAR(100),
    g2b_bid_ntce_ord VARCHAR(20),
    department_code VARCHAR(50),
    project_name VARCHAR(500) NOT NULL,
    order_client VARCHAR(300),
    design_amt NUMERIC(19, 2),
    bid_type VARCHAR(50),
    announce_date VARCHAR(8),
    pq_regist_date VARCHAR(12),
    pq_submit_date VARCHAR(12),
    order_method VARCHAR(50),
    bid_date VARCHAR(12),
    interview_date VARCHAR(8),
    bid_sucess_yn VARCHAR(1),
    pq_decide_empno VARCHAR(50),
    pq_decide_date VARCHAR(8),
    super_decide_empno VARCHAR(50),
    participate_yn VARCHAR(1),

    created_at TIMESTAMP,
    created_id VARCHAR(100),
    last_changed_at TIMESTAMP,
    last_changed_id VARCHAR(100),
    business_type VARCHAR(50),
    bid_closing_date VARCHAR(12),
    process_tag VARCHAR(50),
    bid_method VARCHAR(50),
    bid_submission VARCHAR(12),
    field_of_work_code VARCHAR(50),
    scope_of_work_code VARCHAR(50),
    reason_of_absence_code VARCHAR(50),
    site_briefing_date VARCHAR(12),
    tp_submit_date VARCHAR(12),
    tp_pass_yn VARCHAR(1),
    prime_contractor VARCHAR(300),
    remark VARCHAR(2000),
    refmat_yn VARCHAR(1)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_bid_notices_g2b_notice
    ON bid_notices (g2b_bid_ntce_no, g2b_bid_ntce_ord);

CREATE INDEX IF NOT EXISTS ix_bid_notices_project_name ON bid_notices (project_name);
CREATE INDEX IF NOT EXISTS ix_bid_notices_order_client ON bid_notices (order_client);
CREATE INDEX IF NOT EXISTS ix_bid_notices_bid_submission ON bid_notices (bid_submission);
CREATE INDEX IF NOT EXISTS ix_bid_notices_department_code ON bid_notices (department_code);
CREATE INDEX IF NOT EXISTS ix_bid_notices_bid_type ON bid_notices (bid_type);
CREATE INDEX IF NOT EXISTS ix_bid_notices_business_type ON bid_notices (business_type);
CREATE INDEX IF NOT EXISTS ix_bid_notices_field_scope ON bid_notices (field_of_work_code, scope_of_work_code);

