-- 공통코드 통합 테이블 DDL 및 초기 데이터
-- 공통 1레벨, 2레벨, 3레벨 엑셀을 하나의 테이블에 적재한다.

DROP TABLE IF EXISTS construction_type CASCADE;

CREATE TABLE construction_type (
    code_id BIGSERIAL PRIMARY KEY,
    code_level SMALLINT NOT NULL,
    level1_code VARCHAR(10) NOT NULL,
    level2_code VARCHAR(10) NOT NULL DEFAULT '',
    level3_code VARCHAR(10) NOT NULL DEFAULT '',
    code_name VARCHAR(100) NOT NULL,
    use_yn BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    created_id VARCHAR(100),
    last_changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    last_changed_id VARCHAR(100),
    CONSTRAINT uk_construction_type UNIQUE (code_level, level1_code, level2_code, level3_code)
);

COMMENT ON TABLE construction_type IS '공통 코드 통합 테이블';
COMMENT ON COLUMN construction_type.code_level IS '원본 레벨';
COMMENT ON COLUMN construction_type.level1_code IS '레벨 1 코드';
COMMENT ON COLUMN construction_type.level2_code IS '레벨 2 코드';
COMMENT ON COLUMN construction_type.level3_code IS '레벨 3 코드';
COMMENT ON COLUMN construction_type.code_name IS '코드명';
COMMENT ON COLUMN construction_type.use_yn IS '사용 여부';
COMMENT ON COLUMN construction_type.created_at IS '생성 시각';
COMMENT ON COLUMN construction_type.created_id IS '생성자 ID';
COMMENT ON COLUMN construction_type.last_changed_at IS '최종 변경 시각';
COMMENT ON COLUMN construction_type.last_changed_id IS '최종 변경자 ID';

CREATE INDEX idx_construction_type_level_path_1 ON construction_type (code_level, level1_code);
CREATE INDEX idx_construction_type_level_path_2 ON construction_type (code_level, level1_code, level2_code);
CREATE INDEX idx_construction_type_level_path_3 ON construction_type (code_level, level1_code, level2_code, level3_code);
CREATE INDEX idx_construction_type_code_name ON construction_type (code_name);

