CREATE TABLE IF NOT EXISTS g2b_bid_notice_sync_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bid_ntce_no VARCHAR(100) NOT NULL,
    bid_ntce_ord VARCHAR(20) NOT NULL,
    bef_bid_bbanc_no VARCHAR(100),
    raw_payload JSONB NOT NULL,
    first_seen_at TIMESTAMPTZ NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL,
    last_api_request_date_from VARCHAR(30),
    last_api_request_date_to VARCHAR(30),
    CONSTRAINT uq_g2b_bid_notice_sync_items UNIQUE (bid_ntce_no, bid_ntce_ord)
);

CREATE INDEX IF NOT EXISTS ix_g2b_bid_notice_sync_items_last_seen
    ON g2b_bid_notice_sync_items (last_seen_at DESC);

COMMENT ON TABLE g2b_bid_notice_sync_items IS '나라장터 용역 입찰공고 API 동기화 이력';
COMMENT ON COLUMN g2b_bid_notice_sync_items.id IS '동기화 이력 식별자';
COMMENT ON COLUMN g2b_bid_notice_sync_items.bid_ntce_no IS '나라장터 입찰공고번호';
COMMENT ON COLUMN g2b_bid_notice_sync_items.bid_ntce_ord IS '나라장터 입찰공고 차수';
COMMENT ON COLUMN g2b_bid_notice_sync_items.bef_bid_bbanc_no IS '재공고의 이전 입찰공고번호';
COMMENT ON COLUMN g2b_bid_notice_sync_items.raw_payload IS '나라장터 API 원본 응답 JSON';
COMMENT ON COLUMN g2b_bid_notice_sync_items.first_seen_at IS '해당 공고를 API에서 최초 확인한 시각';
COMMENT ON COLUMN g2b_bid_notice_sync_items.last_seen_at IS '해당 공고를 API에서 마지막 확인한 시각';
COMMENT ON COLUMN g2b_bid_notice_sync_items.last_api_request_date_from IS '마지막 API 조회 시작 시각';
COMMENT ON COLUMN g2b_bid_notice_sync_items.last_api_request_date_to IS '마지막 API 조회 종료 시각';
