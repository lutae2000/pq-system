CREATE TABLE pq_new_employment_employees (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  base_year_month CHAR(7) NOT NULL,
  employee_no VARCHAR(30),
  employee_name VARCHAR(100) NOT NULL,
  birth_date CHAR(8),
  hire_date CHAR(8) NOT NULL,
  department_code VARCHAR(30) NOT NULL,
  job_category VARCHAR(100),
  remark VARCHAR(1000),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_id VARCHAR(100),
  last_changed_at TIMESTAMP,
  last_changed_id VARCHAR(100),
  CONSTRAINT uq_pq_new_employment_employee UNIQUE (base_year_month, employee_no, employee_name, hire_date)
);

CREATE INDEX ix_pq_new_employment_employees_01
  ON pq_new_employment_employees (base_year_month, department_code, employee_name);

/* 신규 고용자 목록 */
SELECT
  hire.id,
  hire.base_year_month,
  hire.employee_no,
  hire.employee_name,
  hire.birth_date,
  hire.hire_date,
  hire.department_code,
  dept.dept_name AS department_name,
  hire.job_category,
  hire.remark,
  hire.created_at,
  hire.created_id,
  hire.last_changed_at,
  hire.last_changed_id
FROM pq_new_employment_employees hire
LEFT JOIN department dept
  ON dept.dept_code = hire.department_code
WHERE (:selected_year_month IS NULL OR hire.base_year_month = :selected_year_month)
  AND (:department_code IS NULL OR hire.department_code = :department_code)
  AND (:employee_name IS NULL OR hire.employee_name LIKE '%' || :employee_name || '%')
ORDER BY hire.hire_date DESC, hire.employee_name;

/* 월별 고용 현황: 월별 고용인원 기준 신규 고용률 */
SELECT
  months.base_year_month,
  COALESCE(monthly_employee_count.employee_count, 0) AS employee_count,
  COUNT(hire.id) AS new_hire_count,
  CASE
    WHEN COALESCE(monthly_employee_count.employee_count, 0) = 0 THEN NULL
    ELSE COUNT(hire.id) * 100.0 / monthly_employee_count.employee_count
  END AS new_hire_rate
FROM monthly_employee_count
LEFT JOIN pq_new_employment_employees hire
  ON hire.base_year_month = monthly_employee_count.base_year_month
  AND (:department_code IS NULL OR hire.department_code = :department_code)
  AND (:employee_name IS NULL OR hire.employee_name LIKE '%' || :employee_name || '%')
JOIN monthly_employee_count months
  ON months.base_year_month = monthly_employee_count.base_year_month
WHERE monthly_employee_count.base_year_month BETWEEN
  COALESCE(:from_year_month, (SELECT MIN(base_year_month) FROM monthly_employee_count))
  AND COALESCE(:base_year_month, (SELECT MAX(base_year_month) FROM monthly_employee_count))
GROUP BY months.base_year_month, monthly_employee_count.employee_count
ORDER BY months.base_year_month;

