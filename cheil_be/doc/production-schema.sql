CREATE FUNCTION cheileng.fn_common_code_name(p_level1_code character varying, p_level2_code character varying) RETURNS character varying
    LANGUAGE sql STABLE
    AS $$
    SELECT fn_common_code_name(p_level1_code, p_level2_code, NULL::VARCHAR)
$$;

CREATE FUNCTION cheileng.fn_common_code_name(p_level1_code character varying, p_level2_code character varying, p_level3_code character varying) RETURNS character varying
    LANGUAGE sql STABLE
    AS $$
    SELECT cc.code_name
    FROM common_codes cc
    WHERE cc.use_yn = TRUE
      AND cc.level1_code = NULLIF(BTRIM(p_level1_code), '')
      AND cc.level2_code = NULLIF(BTRIM(p_level2_code), '')
      AND cc.level3_code IS NOT DISTINCT FROM NULLIF(BTRIM(p_level3_code), '')
    LIMIT 1
$$;

CREATE FUNCTION cheileng.fn_user_menu_permissions(p_login_id character varying) RETURNS TABLE(menu_code character varying, menu_name character varying, parent_menu_code character varying, menu_path character varying, menu_type character varying, sort_seq integer, use_yn boolean, visible_yn boolean, read_yn boolean, create_yn boolean, update_yn boolean, delete_yn boolean)
    LANGUAGE sql STABLE
    AS $$
    SELECT
    m.menu_code,
    m.menu_name,
    m.parent_menu_code,
    m.menu_path,
    m.menu_type,
    m.sort_seq,
    m.use_yn,
    m.visible_yn,
    COALESCE(rp.read_yn, false) OR COALESCE(up.read_yn, false) AS read_yn,
    COALESCE(rp.create_yn, false) OR COALESCE(up.create_yn, false) AS create_yn,
    COALESCE(rp.update_yn, false) OR COALESCE(up.update_yn, false) AS update_yn,
    COALESCE(rp.delete_yn, false) OR COALESCE(up.delete_yn, false) AS delete_yn
FROM system_menus m
JOIN auth_users au
    ON au.login_id = p_login_id
LEFT JOIN role_permissions rp
    ON rp.menu_code = m.menu_code
   AND rp.role_code = au.group_code
LEFT JOIN user_menu_permissions up
    ON up.menu_code = m.menu_code
   AND up.login_id = au.login_id
WHERE m.use_yn = true
  AND m.visible_yn = true
  and AU.use_yn = true
ORDER BY m.sort_seq, m.menu_code
$$;

