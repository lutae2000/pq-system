import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, "..");
const appDir = path.join(projectRoot, "app");
const pathsOutputFile = path.join(projectRoot, "shared", "navigation", "pagePaths.generated.ts");
const registryOutputFile = path.join(projectRoot, "shared", "navigation", "pageRegistry.generated.tsx");
const excludedRoutes = new Set(["/", "/login"]);

async function findPageFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      files.push(...(await findPageFiles(fullPath)));
      continue;
    }

    if (entry.isFile() && entry.name === "page.tsx") {
      files.push(fullPath);
    }
  }

  return files;
}

function toRoutePath(pageFile) {
  const relativeDir = path.relative(appDir, path.dirname(pageFile));
  if (!relativeDir) {
    return "/";
  }
  return `/${relativeDir.split(path.sep).join("/")}`;
}

function normalizeSource(source) {
  return `${source.trim()}\n`;
}

function parsePageComponent(pageFile, source) {
  const importMatch = source.match(/import\s+\{\s*([A-Za-z0-9_]+)\s*\}\s+from\s+"([^"]+)";/);

  if (!importMatch) {
    throw new Error(`Unable to parse page component import from ${pageFile}`);
  }

  return {
    exportName: importMatch[1],
    modulePath: importMatch[2],
  };
}

const pageFiles = (await findPageFiles(appDir))
  .map((pageFile) => ({ pageFile, routePath: toRoutePath(pageFile) }))
  .filter(({ routePath }) => !excludedRoutes.has(routePath))
  .sort((left, right) => left.routePath.localeCompare(right.routePath));

const pageEntries = await Promise.all(
  pageFiles.map(async ({ pageFile, routePath }, index) => {
    const source = await readFile(pageFile, "utf8");
    const { exportName, modulePath } = parsePageComponent(pageFile, source);

    return {
      exportName,
      importAlias: `GeneratedPageComponent${index}`,
      modulePath,
      routePath,
    };
  }),
);

const pathEntries = pageEntries
  .map(({ routePath }) => `  "${routePath}",`)
  .join("\n");

const generatedPaths = normalizeSource(`
/* This file is generated by scripts/generate-page-registry.mjs.
 * Do not edit manually. It intentionally contains only route path strings
 * so menu/admin code can validate system_menus.menuPath without importing
 * page components.
 */

export const generatedPagePaths = [
${pathEntries}
] as const;

export type GeneratedPagePath = (typeof generatedPagePaths)[number];
`);

const registryImports = pageEntries
  .map(
    ({ exportName, importAlias, modulePath }) => `import { ${exportName} as ${importAlias} } from "${modulePath}";`,
  )
  .join("\n");

const registryEntries = pageEntries
  .map(({ importAlias, routePath }) => `  "${routePath}": ${importAlias},`)
  .join("\n");

const generatedRegistry = normalizeSource(`
"use client";

/* This file is generated by scripts/generate-page-registry.mjs.
 * Do not edit manually. It maps menu route paths to client page components
 * so the tab outlet can keep mounted pages alive across tab switches.
 */

import type { ComponentType } from "react";
${registryImports}

import type { GeneratedPagePath } from "@/shared/navigation/pagePaths.generated";

export const pageRegistry: Record<GeneratedPagePath, ComponentType> = {
${registryEntries}
};
`);

const currentPaths = await readFile(pathsOutputFile, "utf8").catch(() => "");
if (currentPaths !== generatedPaths) {
  await writeFile(pathsOutputFile, generatedPaths, "utf8");
}

const currentRegistry = await readFile(registryOutputFile, "utf8").catch(() => "");
if (currentRegistry !== generatedRegistry) {
  await writeFile(registryOutputFile, generatedRegistry, "utf8");
}
